    <h1>Déclaration d'accessibilité</h1>

    <p>
      Le collectif SSA Pays de Morlaix s'engage à rendre ce site accessible au plus
      grand nombre, conformément au Référentiel général d'amélioration de
      l'accessibilité (RGAA) et aux critères WCAG.
    </p>

    <h2>État de conformité</h2>
    <p class="legal-todo">
      <strong>À compléter après audit :</strong> état de conformité au RGAA
      (non conforme, partiellement conforme ou totalement conforme). Tant qu'aucun
      audit n'a été réalisé, l'état par défaut à déclarer est « non conforme ».
    </p>

    <h2>Résultats des tests</h2>
    <p class="legal-todo">
      <strong>À compléter :</strong> taux de conformité aux critères RGAA issu de
      l'audit, et date de l'audit.
    </p>

    <h2>Contenus non accessibles</h2>
    <p class="legal-todo">
      <strong>À compléter :</strong> liste des non-conformités relevées lors de
      l'audit et, le cas échéant, des dérogations pour charge disproportionnée.
    </p>

    <h2>Établissement de cette déclaration</h2>
    <p class="legal-todo">
      <strong>À compléter :</strong> date d'établissement de la déclaration et
      méthode d'évaluation utilisée (auto-évaluation ou audit par un tiers).
    </p>

    <h2>Retour d'information et contact</h2>
    <p>
      Si vous rencontrez un défaut d'accessibilité vous empêchant d'accéder à un
      contenu, contactez-nous à
      <a href="mailto:ssapaysdemorlaix@mailo.com">ssapaysdemorlaix@mailo.com</a>
      afin que nous puissions vous orienter vers une solution adaptée.
    </p>

    <h2>Voie de recours</h2>
    <p>
      Si vous constatez un défaut d'accessibilité et que, après nous avoir signalé
      le problème, vous n'obtenez pas de réponse satisfaisante, vous pouvez saisir
      le Défenseur des droits
      (<a href="https://www.defenseurdesdroits.fr/" target="_blank" rel="noopener noreferrer">defenseurdesdroits.fr</a>).
    </p>
